function faqToText(node: React.ReactNode): string {
  if (typeof node === 'string') return node;
  if (typeof node === 'number') return String(node);
  if (Array.isArray(node)) return node.map(faqToText).join(' ');
  if (node && typeof node === 'object' && 'props' in node) {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    return faqToText((node as any).props.children);
  }
  return '';
}

export default function FAQ() {
  const faqSchema = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: faqs.map((f) => ({
      '@type': 'Question',
      name: f.q,
      acceptedAnswer: { '@type': 'Answer', text: faqToText(f.a) },
    })),
  };

  return (
    <section className="faq" id="faq">
      <JsonLd data={faqSchema} />
      <div className="container">
        <SectionHeader
          eyebrow="שאלות נפוצות"
          titleHtml="השאלות שכולם<br>שואלים בשיחה הראשונה."
          description="אם יש לך שאלה שלא מופיעה כאן, שלח לנו הודעה בוואטסאפ. אין שאלה טפשית."
        />

        <ScrollTextHighlight className="faq-list" dimOpacity={0.2} blurAmount={1}>
          {faqs.map((faq) => (
            <FAQItem key={faq.q} question={faq.q}>
              {faq.a}
            </FAQItem>
          ))}
        </ScrollTextHighlight>
      </div>
    </section>
  );
}
